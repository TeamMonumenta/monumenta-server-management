package com.playmonumenta.gradleconfig

import org.gradle.api.DefaultTask
import org.gradle.api.file.DirectoryProperty
import org.gradle.api.provider.MapProperty
import org.gradle.api.provider.Property
import org.gradle.api.tasks.CacheableTask
import org.gradle.api.tasks.Input
import org.gradle.api.tasks.OutputDirectory
import org.gradle.api.tasks.TaskAction

/**
 * Generates a Java class of compile-time string constants, such as the build version.
 *
 * Annotation values must be compile-time constants, so this is how a version computed by
 * the build reaches an annotation. The main user is Velocity's `@Plugin`, whose
 * `version = BuildConstants.VERSION` is copied into the generated velocity-plugin.json.
 */
@CacheableTask
abstract class GenerateBuildConstants : DefaultTask() {
    /** Package of the generated class, e.g. `com.playmonumenta.networkrelay`. */
    @get:Input
    abstract val packageName: Property<String>

    /** Simple name of the generated class. */
    @get:Input
    abstract val className: Property<String>

    /** Constant name to value. Names must be valid Java identifiers. */
    @get:Input
    abstract val constants: MapProperty<String, String>

    @get:OutputDirectory
    abstract val outputDir: DirectoryProperty

    @TaskAction
    fun generate() {
        val pkg = packageName.get()
        val cls = className.get()
        require(pkg.split('.').all(::isJavaIdentifier)) { "invalid package name: $pkg" }
        require(isJavaIdentifier(cls)) { "invalid class name: $cls" }

        val fields = constants.get().toSortedMap().map { (name, value) ->
            require(isJavaIdentifier(name)) { "invalid constant name: $name" }
            "\tpublic static final String $name = \"${escapeJava(value)}\";\n"
        }

        val dir = outputDir.get().asFile
        dir.deleteRecursively()
        val file = dir.resolve(pkg.replace('.', '/')).resolve("$cls.java")
        file.parentFile.mkdirs()
        // Tabs and this layout match Monumenta's Java style, so the class passes the same
        // checkstyle and PMD rules as hand-written code.
        file.writeText(buildString {
            append("// Generated by the ${name} Gradle task. Do not edit.\n\n")
            append("package $pkg;\n\n")
            append("/** Values fixed at build time. */\n")
            append("public final class $cls {\n")
            fields.forEach { append(it) }
            append("\n\tprivate $cls() {\n\t}\n")
            append("}\n")
        })
    }

    private fun isJavaIdentifier(s: String): Boolean =
        s.isNotEmpty() && Character.isJavaIdentifierStart(s[0]) && s.drop(1).all(Character::isJavaIdentifierPart)

    private fun escapeJava(s: String): String = buildString {
        for (c in s) {
            when {
                c == '\\' -> append("\\\\")
                c == '"' -> append("\\\"")
                c == '\n' -> append("\\n")
                c == '\r' -> append("\\r")
                c == '\t' -> append("\\t")
                c < ' ' || c > '~' -> append("\\u%04x".format(c.code))
                else -> append(c)
            }
        }
    }
}
